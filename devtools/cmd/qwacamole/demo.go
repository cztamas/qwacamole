func writeJSON(path string, v any) error {
	b, e := json.MarshalIndent(v, "", "  ")
	if e != nil {
		return e
	}
	return os.WriteFile(path, b, 0600)
}
func demo(dir string) error {
	abs, e := filepath.Abs(dir)
	if e != nil {
		return e
	}
	dir = abs
	if e = os.MkdirAll(dir, 0700); e != nil {
		return e
	}
	if e = os.WriteFile(filepath.Join(dir, ".qwacamole-state"), []byte("generated by qwacamole demo\n"), 0600); e != nil {
		return e
	}
	pkidir := filepath.Join(dir, "pki")
	if _, e = os.Stat(filepath.Join(pkidir, "qwac-root.pem")); os.IsNotExist(e) {
		if e = pki.Generate(pkidir, pki.Identity{Host: "qwac.example.com", Organization: "Qwacamole Synthetic Organization TEST", Country: "HU", Locality: "Budapest", Registration: "NTRHU-TEST-0001"}); e != nil {
			return e
		}
	}
	_ = os.MkdirAll(filepath.Join(dir, "evidence"), 0700)
	_ = os.MkdirAll(filepath.Join(dir, "bindings"), 0700)
	config := map[string]any{"pebble": map[string]any{"listenAddress": "127.0.0.1:14000", "managementListenAddress": "127.0.0.1:15000", "certificate": filepath.Join(pkidir, "acme-leaf.pem"), "privateKey": filepath.Join(pkidir, "acme-leaf-key.pem"), "httpPort": 5002, "tlsPort": 5001, "profiles": map[string]any{"default": map[string]any{"description": "Qwacamole short-lived local test", "validityPeriod": 360}}, "retryAfter": map[string]int{"authz": 1, "order": 1}}}
	if e = writeJSON(filepath.Join(dir, "pebble.json"), config); e != nil {
		return e
	}
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()
	mux := dns.NewServeMux()
	mux.HandleFunc(".", func(w dns.ResponseWriter, r *dns.Msg) {
		m := new(dns.Msg)
		m.SetReply(r)
		for _, q := range r.Question {
			if q.Name == "qwac.example.com." {
				if q.Qtype == dns.TypeA {
					m.Answer = append(m.Answer, &dns.A{Hdr: dns.RR_Header{Name: q.Name, Rrtype: dns.TypeA, Class: dns.ClassINET, Ttl: 0}, A: []byte{127, 0, 0, 1}})
				}
			} else {
				m.Rcode = dns.RcodeNameError
			}
		}
		_ = w.WriteMsg(m)
	})
	ds := &dns.Server{Addr: "127.0.0.1:8053", Net: "udp", Handler: mux}
	dnsErr := make(chan error, 1)
	go func() { dnsErr <- ds.ListenAndServe() }()
	defer ds.Shutdown()
	children := []*exec.Cmd{}
	defer func() {
		for n := len(children) - 1; n >= 0; n-- {
			_ = children[n].Process.Signal(syscall.SIGTERM)
		}
		for _, c := range children {
			_ = c.Wait()
		}
	}()
	start := func(path, logname string, args ...string) error {
		f, e := os.OpenFile(filepath.Join(dir, "evidence", logname), os.O_CREATE|os.O_APPEND|os.O_WRONLY, 0600)
		if e != nil {
			return e
		}
		defer f.Close()
		c := exec.Command(path, args...)
		c.Stdout = f
		c.Stderr = f
		c.Env = append(os.Environ(), "XDG_DATA_HOME="+filepath.Join(dir, "xdg-data"), "XDG_CONFIG_HOME="+filepath.Join(dir, "xdg-config"), "PEBBLE_VA_NOSLEEP=1", "PEBBLE_VA_ALWAYS_VALID=0", "PEBBLE_AUTHZREUSE=0", "PEBBLE_WFE_NONCEREJECT=0")
		if e = c.Start(); e != nil {
			return e
		}
		children = append(children, c)
		return nil
	}
	if e = start(".tools/bin/pebble", "pebble.log", "-config", filepath.Join(dir, "pebble.json"), "-dnsserver", "127.0.0.1:8053"); e != nil {
		return e
	}
	acmeRoot, e := pki.ReadCert(filepath.Join(pkidir, "acme-root.pem"))
	if e != nil {
		return e
	}
	pool := x509.NewCertPool()
	pool.AddCert(acmeRoot)
	client := &http.Client{Transport: &http.Transport{TLSClientConfig: &tls.Config{RootCAs: pool}}, Timeout: time.Second}
	var roots []byte
	for end := time.Now().Add(15 * time.Second); time.Now().Before(end); {
		res, err := client.Get("https://localhost:15000/roots/0")
		if err == nil {
			roots, err = io.ReadAll(res.Body)
			res.Body.Close()
			if err == nil && res.StatusCode == 200 {
				break
			}
		}
		time.Sleep(200 * time.Millisecond)
	}
	if len(roots) == 0 {
		return fmt.Errorf("Pebble root unavailable; inspect pebble.log")
	}
	if e = os.WriteFile(filepath.Join(pkidir, "pebble-root.pem"), roots, 0600); e != nil {
		return e
	}
	binding := map[string]any{"directory": filepath.Join(dir, "bindings"), "chain_files": []string{filepath.Join(pkidir, "qwac-leaf.pem"), filepath.Join(pkidir, "qwac-intermediate.pem"), filepath.Join(pkidir, "qwac-root.pem")}, "trust_files": []string{filepath.Join(pkidir, "qwac-root.pem")}, "key_file": filepath.Join(pkidir, "qwac-leaf-key.pem"), "hostname": "qwac.example.com", "lifetime": int64(45 * time.Second)}
	if _, err := os.Stat(filepath.Join(dir, "firefox-compatibility")); err == nil {
		binding["firefox_compatibility"] = true
	}
	caddyConfig := map[string]any{"admin": map[string]any{"listen": "127.0.0.1:2019"}, "storage": map[string]any{"module": "file_system", "root": filepath.Join(dir, "caddy-storage")}, "apps": map[string]any{"tls": map[string]any{"automation": map[string]any{"renew_interval": "2s", "policies": []any{map[string]any{"subjects": []string{"qwac.example.com"}, "renewal_window_ratio": 0.8, "issuers": []any{map[string]any{"module": "qwac_demo", "binding": binding, "acme": map[string]any{"ca": "https://localhost:14000/dir", "test_ca": "https://localhost:14000/dir", "trusted_roots_pem_files": []string{filepath.Join(pkidir, "acme-root.pem")}, "challenges": map[string]any{"http": map[string]any{"alternate_port": 5002}, "tls-alpn": map[string]any{"disabled": true}}}}}}}}}, "http": map[string]any{"http_port": 5002, "https_port": 8443, "servers": map[string]any{"demo": map[string]any{"listen": []string{"127.0.0.1:8443"}, "automatic_https": map[string]any{"disable_redirects": true}, "tls_connection_policies": []any{map[string]any{}}, "protocols": []string{"h1", "h2"}, "routes": []any{map[string]any{"match": []any{map[string]any{"path": []string{"/init"}}}, "handle": []any{map[string]any{"handler": "qwac_demo", "binding": binding, "pki": pkidir}}}, map[string]any{"match": []any{map[string]any{"host": []string{"qwac.example.com"}}}, "handle": []any{map[string]any{"handler": "qwac_demo_binding", "binding": binding}, map[string]any{"handler": "qwac_demo", "binding": binding, "pki": pkidir}}}}}, "challenge": map[string]any{"listen": []string{"127.0.0.1:5002"}, "routes": []any{map[string]any{"handle": []any{map[string]any{"handler": "qwac_demo", "pki": pkidir, "public_pki_only": true}}}}}}}}}
	// A separate loopback HTTP intermediary stores the origin response with its
	// Link. The browser-facing /cached route bypasses binding middleware, proving
	// that discovery survives without regenerating headers on cache hits.
	cacheRoots := x509.NewCertPool()
	if !cacheRoots.AppendCertsFromPEM(roots) {
		return fmt.Errorf("cache TLS authority unavailable")
	}
	cacheTransport := &http.Transport{TLSClientConfig: &tls.Config{RootCAs: cacheRoots}, DialContext: func(ctx context.Context, network, _ string) (net.Conn, error) {
		return (&net.Dialer{}).DialContext(ctx, network, "127.0.0.1:8443")
	}, ForceAttemptHTTP2: true}
	defer cacheTransport.CloseIdleConnections()
	cache := &cacheproxy.Proxy{Origin: "https://qwac.example.com:8443/cache-origin", Client: &http.Client{Transport: cacheTransport, Timeout: 5 * time.Second}}
	intermediary := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.URL.Path == "/counts" {
			requests, hits := cache.Counts()
			_ = json.NewEncoder(w).Encode(map[string]int{"requests": requests, "hits": hits})
			return
		}
		cache.ServeHTTP(w, r)
	}))
	defer intermediary.Close()
	if e = writeJSON(filepath.Join(dir, "evidence/cache-intermediary.json"), map[string]string{"address": intermediary.URL, "origin": cache.Origin}); e != nil {
		return e
	}
	server := caddyConfig["apps"].(map[string]any)["http"].(map[string]any)["servers"].(map[string]any)["demo"].(map[string]any)
	server["routes"] = append([]any{map[string]any{"match": []any{map[string]any{"host": []string{"qwac.example.com"}, "path": []string{"/cached"}}}, "handle": []any{map[string]any{"handler": "reverse_proxy", "upstreams": []any{map[string]any{"dial": intermediary.Listener.Addr().String()}}}}, "terminal": true}}, server["routes"].([]any)...)
	if e = writeJSON(filepath.Join(dir, "caddy.json"), caddyConfig); e != nil {
		return e
	}
	if e = start("bin/caddy", "caddy.log", "run", "--config", filepath.Join(dir, "caddy.json")); e != nil {
		return e
	}
	fmt.Println("Demo running on https://qwac.example.com:8443 (browser maps it to loopback). Ctrl-C cleans up project child processes.")
	tick := time.NewTicker(time.Second)
	defer tick.Stop()
	for {
		select {
		case <-ctx.Done():
			return nil
		case e = <-dnsErr:
			return e
		case <-tick.C:
			request := filepath.Join(dir, "restart-request")
			if _, err := os.Stat(request); err == nil {
				old := children[len(children)-1]
				oldPID := old.Process.Pid
				_ = old.Process.Signal(syscall.SIGTERM)
				_ = old.Wait()
				children = children[:len(children)-1]
				if e = start("bin/caddy", "caddy.log", "run", "--config", filepath.Join(dir, "caddy.json")); e != nil {
					return e
				}
				_ = writeJSON(filepath.Join(dir, "evidence/restart.json"), map[string]any{"old_caddy_pid": oldPID, "new_caddy_pid": children[len(children)-1].Process.Pid, "pebble_pid_unchanged": children[0].Process.Pid})
				_ = os.Remove(request)
			}
		}
	}
}
