// browserDemo owns one fresh state, one service supervisor, and one visible
// browser. Every invocation starts with a matching Pebble root and browser copy.
func browserDemo(base, binary, metadata string, owner pki.Identity) error {
	return visibleDemo(base, binary, metadata, "", "", owner, false)
}

func firefoxDemo(base, binary, driver, certutil string, owner pki.Identity) error {
	return visibleDemo(base, binary, "", driver, certutil, owner, true)
}

func visibleDemo(base, binary, metadata, driver, certutil string, owner pki.Identity, firefox bool) error {
	if firefox {
		if binary == "" {
			var err error
			binary, err = browser.DetectFirefox()
			if err != nil {
				return err
			}
		}
		if driver == "" {
			driver = ".tools/bin/geckodriver"
		}
		if _, err := os.Stat(driver); err != nil {
			return fmt.Errorf("install geckodriver with scripts/bootstrap-firefox.sh or pass -geckodriver: %w", err)
		}
		if certutil == "" {
			var err error
			certutil, err = exec.LookPath("certutil")
			if err != nil {
				return fmt.Errorf("install NSS certutil (brew install nss) or pass -certutil: %w", err)
			}
		}
	} else if binary == "" || metadata == "" {
		b, m, err := browser.Detect()
		if err != nil {
			return err
		}
		if binary == "" {
			binary = b
		}
		if metadata == "" {
			metadata = m
		}
	}
	if err := checkDemoPorts(); err != nil {
		return err
	}
	base, err := filepath.Abs(base)
	if err != nil {
		return err
	}
	if err = os.MkdirAll(base, 0700); err != nil {
		return err
	}
	dir, err := os.MkdirTemp(base, "browser-demo-")
	if err != nil {
		return err
	}
	if err = os.WriteFile(filepath.Join(dir, ".qwacamole-state"), []byte("generated by qwacamole browser-demo\n"), 0600); err != nil {
		return err
	}
	fmt.Println("Demo state and evidence:", dir)
	generate := pki.Generate
	if firefox {
		generate = pki.GenerateFirefox
	}
	if err = generate(filepath.Join(dir, "pki"), owner); err != nil {
		return err
	}
	if firefox {
		if err = os.WriteFile(filepath.Join(dir, "firefox-compatibility"), []byte("Firefox 157 compatibility: omit crit; use Mozilla public test QWAC authority\n"), 0600); err != nil {
			return err
		}
	}
	if err = os.MkdirAll(filepath.Join(dir, "evidence"), 0700); err != nil {
		return err
	}
	exe, err := os.Executable()
	if err != nil {
		return err
	}
	log, err := os.OpenFile(filepath.Join(dir, "evidence/demo-console.log"), os.O_CREATE|os.O_WRONLY, 0600)
	if err != nil {
		return err
	}
	defer log.Close()
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()
	child := exec.Command(exe, "demo", "-state", dir)
	child.Stdout, child.Stderr = log, log
	if err = child.Start(); err != nil {
		return err
	}
	done := make(chan struct{})
	var serviceErr error
	go func() {
		serviceErr = child.Wait()
		close(done)
	}()
	defer func() {
		select {
		case <-done:
		default:
			_ = child.Process.Signal(syscall.SIGTERM)
			<-done
		}
	}()
	deadline := time.NewTimer(30 * time.Second)
	defer deadline.Stop()
	tick := time.NewTicker(200 * time.Millisecond)
	defer tick.Stop()
	ready := false
	for !ready {
		select {
		case <-ctx.Done():
			return ctx.Err()
		case <-done:
			return fmt.Errorf("demo services stopped during startup: %v; inspect %s", serviceErr, dir)
		case <-deadline.C:
			return fmt.Errorf("ACME/binding startup timed out; inspect %s", dir)
		case <-tick.C:
			_, err = os.Stat(filepath.Join(dir, "bindings/current.json"))
			ready = err == nil
		}
	}
	tlsRoot, err := pki.ReadCert(filepath.Join(dir, "pki/pebble-root.pem"))
	if err != nil {
		return err
	}
	qwacRoot, err := pki.ReadCert(filepath.Join(dir, "pki/qwac-root.pem"))
	if err != nil {
		return err
	}
	profile := filepath.Join(dir, "profiles/interactive")
	if firefox {
		err = browser.PrepareFirefox(profile, certutil, tlsRoot, true, true)
	} else {
		err = browser.Prepare(profile, metadata, tlsRoot, qwacRoot, true, true)
	}
	if err != nil {
		return err
	}
	// A service supervisor exit also closes its browser; no unrelated process
	// is ever signalled. Cancellation below is local to this invocation.
	browserStop, stopBrowser := context.WithCancel(ctx)
	defer stopBrowser()
	go func() {
		select {
		case <-done:
			stopBrowser()
		case <-browserStop.Done():
		}
	}()
	if firefox {
		fmt.Printf("Expected native Firefox owner: %s [%s]; Qualified as specified in Regulation (EU) 2024/1183.\n", owner.Organization, owner.Country)
		fmt.Println("Firefox compatibility binding omits crit and uses Mozilla's public test QWAC authority in this isolated profile.")
		qwacLeaf, err := pki.ReadCert(filepath.Join(dir, "pki/qwac-leaf.pem"))
		if err != nil {
			return err
		}
		result, runErr := browser.RunFirefox(browserStop, browser.FirefoxOptions{Binary: binary, Driver: driver, Profile: profile, URL: "https://qwac.example.com:8443/", Evidence: filepath.Join(dir, "evidence"), Visible: true, ExpectedQWAC: qwacLeaf})
		if err = writeJSON(filepath.Join(dir, "evidence/firefox-result.json"), result); err != nil {
			return err
		}
		if runErr != nil {
			return runErr
		}
		select {
		case <-done:
			if ctx.Err() == nil {
				return fmt.Errorf("demo services stopped while Firefox was open: %v", serviceErr)
			}
		default:
		}
		if err = browser.AssertFirefox(result, "positive", qwacLeaf); err != nil {
			return err
		}
		fmt.Println("PASS native Firefox QWAC verification; evidence:", filepath.Join(dir, "evidence"))
		return nil
	}
	fmt.Printf("Expected native status: EU Qualified Status — Issued to: %s [%s]\n", owner.Organization, owner.Country)
	chromeLog, err := os.OpenFile(filepath.Join(dir, "evidence/chrome-console.log"), os.O_CREATE|os.O_WRONLY, 0600)
	if err != nil {
		return err
	}
	defer chromeLog.Close()
	result, runErr := browser.Open(browserStop, browser.Options{Binary: binary, Profile: profile,
		URL: "https://qwac.example.com:8443/", InitURL: "https://qwac.example.com:8443/init",
		NetLog: filepath.Join(dir, "evidence/interactive-netlog.json"), CTException: true, Console: chromeLog})
	stopBrowser()
	select {
	case <-done:
		if ctx.Err() == nil {
			return fmt.Errorf("demo services stopped while browser was open: %v; inspect %s", serviceErr, dir)
		}
	default:
	}
	if err = writeJSON(filepath.Join(dir, "evidence/interactive-result.json"), result); err != nil {
		return err
	}
	if runErr != nil {
		return runErr
	}
	if err = browser.Assert(result, "positive", qwacRoot); err != nil {
		return err
	}
	fmt.Println("PASS native Chrome QWAC verification; evidence:", filepath.Join(dir, "evidence"))
	return nil
}

func checkDemoPorts() error {
	return checkPorts([]demoPort{{"tcp", "8443"}, {"tcp", "5002"}, {"tcp", "14000"}, {"tcp", "15000"}, {"tcp", "2019"}, {"udp", "8053"}})
}

type demoPort struct{ network, port string }

func checkPorts(ports []demoPort) error {
	for _, port := range ports {
		var resource io.Closer
		var err error
		address := "127.0.0.1:" + port.port
		if port.network == "udp" {
			resource, err = net.ListenPacket("udp", address)
		} else {
			resource, err = net.Listen("tcp", address)
		}
		if err != nil {
			return fmt.Errorf("demo %s port %s unavailable: %w; only one demo can run at a time: close its browser or stop its terminal first", port.network, port.port, err)
		}
		defer resource.Close()
	}
	return nil
}
