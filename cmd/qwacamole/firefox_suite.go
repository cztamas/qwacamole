package main

import (
	"context"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"time"

	"github.com/cztamas/qwacamole/internal/browser"
	"github.com/cztamas/qwacamole/internal/pki"
)

// Like browser-suite, this checks a separately running fixture server.
func firefoxSuite(dir, binary, driver, certutil string) error {
	if _, err := os.Stat(filepath.Join(dir, "firefox-compatibility")); err != nil {
		return fmt.Errorf("use a state generated by firefox-demo: %w", err)
	}
	var err error
	if binary == "" {
		binary, err = browser.DetectFirefox()
		if err != nil {
			return err
		}
	}
	if driver == "" {
		driver = ".tools/bin/geckodriver"
	}
	if certutil == "" {
		certutil, err = exec.LookPath("certutil")
		if err != nil {
			return err
		}
	}
	tlsRoot, err := pki.ReadCert(filepath.Join(dir, "pki/tls-root.pem"))
	if err != nil {
		return err
	}
	qwac, err := pki.ReadCert(filepath.Join(dir, "pki/qwac-leaf.pem"))
	if err != nil {
		return err
	}
	tests := []struct {
		name, path, expect string
		tls, qwac          bool
	}{
		{"positive", "9443/positive", "positive", true, true},
		{"no-qwac-trust", "9443/positive", "no-qwac-trust", true, false},
		{"no-tls-trust", "9443/positive", "tls-untrusted", false, true},
		{"signature", "9443/signature", "signature", true, true},
		{"wrong-tls", "9443/wrong-tls", "wrong-tls", true, true},
		{"qwac-hostname", "9443/qwac-hostname", "qwac-hostname", true, true},
		{"expired-binding", "9443/expired-binding", "expired-binding", true, true},
		{"qwac-profile", "9443/qwac-profile", "qwac-profile", true, true},
		{"tls-hostname", "9444/positive", "tls-hostname", true, true},
		{"tls-expiry", "9445/positive", "tls-expiry", true, true},
		{"critical-header", "9443/critical-header", "critical-header", true, true},
	}
	results := map[string]any{}
	failures := 0
	for _, tc := range tests {
		profile := filepath.Join(dir, "profiles", "firefox-"+tc.name+fmt.Sprint(time.Now().UnixNano()))
		if err = browser.PrepareFirefox(profile, certutil, tlsRoot, tc.tls, tc.qwac); err != nil {
			return err
		}
		evidence := filepath.Join(dir, "evidence", "firefox-suite-"+tc.name)
		if err = os.MkdirAll(evidence, 0700); err != nil {
			return err
		}
		r, runErr := browser.RunFirefox(context.Background(), browser.FirefoxOptions{Binary: binary, Driver: driver, Profile: profile, URL: "https://qwac.example.com:" + tc.path, Evidence: evidence})
		if runErr == nil {
			runErr = browser.AssertFirefox(r, tc.expect, qwac)
		}
		entry := map[string]any{"passed": runErr == nil, "browser_version": r.Version}
		if runErr != nil {
			entry["error"] = runErr.Error()
			failures++
			fmt.Println("FAIL", tc.name, runErr)
		} else {
			fmt.Println("PASS", tc.name)
		}
		results[tc.name] = entry
		if err = writeJSON(filepath.Join(evidence, "firefox-result.json"), r); err != nil {
			return err
		}
		if err = writeJSON(filepath.Join(dir, "evidence/firefox-suite.json"), results); err != nil {
			return err
		}
	}
	if failures != 0 {
		return fmt.Errorf("%d native Firefox checks failed; see %s", failures, filepath.Join(dir, "evidence/firefox-suite.json"))
	}
	return nil
}
